def get_text(key: str, lang: str) -> str:
    """Get translation for given key and language."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    return lang_dict.get(key, key)


def get_available_languages() -> list[str]:
    """Return list of available language codes."""
    return list(TRANSLATIONS.keys())


def validate_key_sets() -> bool:
    """Assert that all languages have identical key sets."""
    key_sets = {lang: set(trans.keys()) for lang, trans in TRANSLATIONS.items()}
    first = next(iter(key_sets.values()))
    return all(ks == first for ks in key_sets.values())
